CREATE SCHEMA IF NOT EXISTS traffic;

-- Create tables in traffic schema
CREATE TABLE IF NOT EXISTS traffic.items (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  sheet_name TEXT,
  article TEXT,
  description TEXT,
  property_number TEXT UNIQUE,
  quantity BIGINT,
  unit TEXT,
  unit_value DOUBLE PRECISION,
  total_value DOUBLE PRECISION,
  date_acquired TEXT,
  remarks TEXT,
  accountable_officer TEXT,
  status TEXT,
  raw_row TEXT
);

CREATE TABLE IF NOT EXISTS traffic.users (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  username TEXT UNIQUE,
  password_hash TEXT,
  role TEXT,
  status TEXT DEFAULT 'approved'
);

CREATE TABLE IF NOT EXISTS traffic.audit_logs (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  username TEXT,
  action TEXT,
  timestamp TEXT,
  details TEXT
);

CREATE TABLE IF NOT EXISTS traffic.sessions (
  sid TEXT PRIMARY KEY,
  sess TEXT,
  expire BIGINT
);

